enum class AppLanguage(
    val code: String,
    val label: String,
    val subtitle: String
) {
    ENGLISH("en", "English", "English (Default)"),
    INDONESIAN("id", "Bahasa Indonesia", "Indonesia"),
    MALAY("ms", "Malaysia", "Bahasa Melayu"),
    FILIPINO("fil", "Philippines", "Filipino / Tagalog");

    companion object {
        fun fromCode(code: String?): AppLanguage {
            return entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: ENGLISH
        }
    }
}

